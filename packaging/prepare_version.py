"""Generate Windows metadata and Inno definitions from app_version.py."""
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
version = runpy.run_path(str(ROOT / 'app_version.py'))['VERSION']
parts = tuple(int(part) for part in version.split('.')) + (0,)
assert len(parts) == 4
file_version = '.'.join(map(str, parts))
(ROOT/'packaging/version_info.txt').write_text(f'''# UTF-8
VSVersionInfo(
  ffi=FixedFileInfo(filevers={parts!r}, prodvers={parts!r},
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[StringFileInfo([StringTable('040904B0', [
    StringStruct('FileDescription', 'PDF LoveR - Offline PDF Tools'),
    StringStruct('FileVersion', '{file_version}'),
    StringStruct('ProductName', 'PDF LoveR'),
    StringStruct('ProductVersion', '{version}'),
    StringStruct('OriginalFilename', 'PDF_LoveR_{version}.exe'),
  ])]), VarFileInfo([VarStruct('Translation', [1033, 1200])])]
)
''', encoding='utf-8')
(ROOT/'packaging/version.iss').write_text(f'''// Generated by prepare_version.py; edit app_version.py instead.
#define AppVersion "{version}"
#define AppFileVersion "{file_version}"
#define AppBaseName "PDF_LoveR_{version}"
''', encoding='utf-8')
